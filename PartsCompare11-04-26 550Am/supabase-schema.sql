-- Enable standard UUID extension
create extension if not exists "uuid-ossp";

-- ------------------------------------------------------------------------
-- 1. Curated HVAC Catalog Offers Table
-- ------------------------------------------------------------------------
create table if not exists public.catalog_offers (
  id bigint generated by default as identity primary key,
  part_id text not null,
  supplier_id text,
  source text not null,
  price_minor integer not null, -- Stored as integer centavos (e.g. ₱295.00 = 29500)
  qty integer not null default 0,
  recorded_quantity integer default 0,
  checked_date text not null default to_char(current_date, 'YYYY-MM-DD'),
  currency text default 'PHP',
  price_basis text default 'per_piece',
  source_reference text,
  active boolean not null default true,
  synthetic boolean not null default false,
  missing boolean not null default false,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now())
);

-- ------------------------------------------------------------------------
-- 2. Job Bill of Materials (BOM) Items Table
-- ------------------------------------------------------------------------
create table if not exists public.bom_items (
  id bigint generated by default as identity primary key,
  list_id text,
  part_id text not null,
  name text,
  qty integer not null check (qty > 0),
  quantity integer check (quantity > 0),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now())
);

-- ------------------------------------------------------------------------
-- 3. Immutable Sourcing Summaries (Frozen Snapshots & Auditable Tokens)
-- ------------------------------------------------------------------------
create table if not exists public.sourcing_summaries (
  id text primary key,
  list_id text,
  save_token text not null,
  name text,
  title text,
  author_name text,
  saved_date text,
  policy_version text,
  review_fingerprint text,
  subtotal_minor integer not null,
  status text not null check (status in ('COMPLETE', 'INCOMPLETE')),
  approval_status text default 'PENDING_APPROVAL',
  approved_by text,
  approved_at timestamp with time zone,
  approval_notes text,
  total_lines integer,
  resolved_count integer,
  unresolved_count integer,
  currency text default 'PHP',
  ai_executive_summary text,
  drift_notice text,
  lines jsonb default '[]'::jsonb,
  snapshot_json jsonb,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- ------------------------------------------------------------------------
-- 4. Immutable Audit Event Ledger Table
-- ------------------------------------------------------------------------
create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  timestamp text not null,
  actor text not null,
  action text not null,
  target text not null,
  details text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- ------------------------------------------------------------------------
-- 5. Enterprise Company Settings & MCDA Utility Weights Table
-- ------------------------------------------------------------------------
create table if not exists public.company_settings (
  id integer primary key default 1 check (id = 1),
  business_name text not null default 'AMGC Airconditioning Services',
  business_type text not null default 'Commercial & Industrial HVAC Services',
  location text not null default 'V.V. Soliven Ave. II, Cainta, Rizal, Philippines',
  currency_code text not null default 'PHP',
  currency_symbol text not null default '₱',
  max_quote_age_days integer not null default 14,
  mcda_cost_weight numeric not null default 0.40,
  mcda_stock_weight numeric not null default 0.30,
  mcda_freshness_weight numeric not null default 0.20,
  mcda_consolidation_weight numeric not null default 0.10,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- ------------------------------------------------------------------------
-- 6. Row-Level Security (RLS) Configuration
-- ------------------------------------------------------------------------
alter table public.catalog_offers enable row level security;
alter table public.bom_items enable row level security;
alter table public.sourcing_summaries enable row level security;
alter table public.audit_logs enable row level security;
alter table public.company_settings enable row level security;

-- Drop previous policies if re-running
drop policy if exists "Allow public access to catalog_offers" on public.catalog_offers;
drop policy if exists "Allow public access to bom_items" on public.bom_items;
drop policy if exists "Allow public access to sourcing_summaries" on public.sourcing_summaries;
drop policy if exists "Allow public access to audit_logs" on public.audit_logs;
drop policy if exists "Allow public access to company_settings" on public.company_settings;

create policy "Allow public access to catalog_offers" on public.catalog_offers for all using (true) with check (true);
create policy "Allow public access to bom_items" on public.bom_items for all using (true) with check (true);
create policy "Allow public access to sourcing_summaries" on public.sourcing_summaries for all using (true) with check (true);
create policy "Allow public access to audit_logs" on public.audit_logs for all using (true) with check (true);
create policy "Allow public access to company_settings" on public.company_settings for all using (true) with check (true);

